def run_sweep(root: Path) -> Dict[str, Any]:
    """Pass counts of :func:`sweep_record` over every chess record built under ``root``."""
    records = [
        record
        for path in sorted({p.parent for p in root.rglob("train_instances.jsonl")})
        for record in read_trace_records(path)
        if record.task in (COLORED_TASK, KIND_TASK)
    ]
    stats: Dict[str, List[int]] = {}
    failures: Dict[str, List[str]] = {}
    quarantined: Dict[str, int] = {}
    for record in records:
        try:
            outcome = sweep_record(record)
        except QuarantineError as exc:
            quarantined[exc.reason] = quarantined.get(exc.reason, 0) + 1
            continue
        for name, problems in outcome.items():
            counts = stats.setdefault(name, [0, 0])
            counts[0] += not problems
            counts[1] += 1
            if problems:
                failures.setdefault(name, []).append(f"{record.instance_id}: {problems}")
    return {"records": len(records), "stats": stats, "failures": failures, "quarantined": quarantined}


@pytest.mark.skipif(not os.environ.get("TRACE_CERT_SWEEP_DIR"), reason="set TRACE_CERT_SWEEP_DIR to run the sweep")
def test_sweep_built_datasets() -> None:
    summary = run_sweep(Path(os.environ["TRACE_CERT_SWEEP_DIR"]))
    print(f"records {summary['records']}, quarantined {summary['quarantined']}")
    for name, (passed, total) in sorted(summary["stats"].items()):
        print(f"{name:40s} {passed}/{total}")
    assert summary["records"] > 0 and not summary["failures"] and not summary["quarantined"]


