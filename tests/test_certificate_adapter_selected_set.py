ELEMENT_MUTATIONS = {
    "bool_index": (lambda m: m.update(annotation_index=True), False),
    "string_index": (lambda m: m.update(annotation_index="0"), False),
    "fractional_index": (lambda m: m.update(annotation_index=0.5), False),
    "upper_color": (lambda m: m.update(color="White"), False),
    "upper_piece": (lambda m: m.update(piece="Pawn"), False),
    "unknown_piece": (lambda m: m.update(piece="unicorn"), False),
    "extra_key": (lambda m: m.update(cell=[0, 0]), False),
    "missing_key": (lambda m: m.pop("color"), False),
    "integral_float_index": (lambda m: m.update(annotation_index=float(m["annotation_index"])), True),
}


@pytest.mark.parametrize("name", sorted(ELEMENT_MUTATIONS))
def test_element_failures(cases, name: str) -> None:
    mutation, element_ok = ELEMENT_MUTATIONS[name]
    case = next(_nonempty(cases))
    obj = sft_object(case["oracle"])
    mutation(obj["certificate"]["members"][0])
    result = score(obj, case["ext"])
    assert result.format == 0.0
    if element_ok:  # scored by value in M, F=0
        assert result.semantics == 1.0 and "integral_float" in result.diagnostics["format_reasons"]
    else:  # the member stays in n and earns nothing
        assert by_id(result)["ss.set.truth"].score < 1.0 and result.semantics < 1.0
