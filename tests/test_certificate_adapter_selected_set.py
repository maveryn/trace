def record_of(entry: Mapping[str, Any]) -> TraceRecord:
    return TraceRecord(train=entry["train"], trace=entry["trace"], image_size=tuple(entry["image_size"]))


def make_extension(record: TraceRecord, oracle: Mapping[str, Any]) -> CertificateExtension:
    """A private extension built by hand (export.py builds the real one)."""
    identity = ADAPTER.identity()
    return CertificateExtension(
        certificate_extension_id=certificate_extension_id(
            instance_id=record.instance_id,
            trace_record_hash=record.trace_record_hash,
            adapter_id=identity["id"],
            adapter_version=identity["version"],
            schema_id=identity["schema_id"],
        ),
        base={
            "instance_id": record.instance_id,
            "trace_record_hash": record.trace_record_hash,
            "task": record.task,
            "query_id": record.query_id,
            "instance_seed": record.instance_seed,
            "instance_version": record.instance_version or "v0",
        },
        adapter=identity,
        labels={
            "answer_gt": record.answer_gt,
            "annotation_gt": record.annotation_gt,
            "reward_contract": record.reward_contract,
        },
        public={"image_size": list(record.source_size())},
        oracle=json.loads(json.dumps(oracle)),
    )


def sft_object(oracle: Mapping[str, Any], seed: int = 0) -> Dict[str, Any]:
    annotation, certificate, answer = ADAPTER.sft_certificate(oracle, seed)
    return {"annotation": annotation, "certificate": certificate, "answer": answer}


def score(obj: Any, ext: CertificateExtension, *, coord_frame: str = "px_source", **kwargs: Any) -> ScoreResult:
    kwargs.setdefault("adapter", ADAPTER)
    text = obj if isinstance(obj, str) else json.dumps(obj)
    row = {"instance_id": ext.instance_id}
    return score_certificate_response(text, row, ext, coord_frame=coord_frame, **kwargs)


def by_id(result: ScoreResult) -> Dict[str, Any]:
    return {check.check_id: check for check in result.checks}


def signals(result: ScoreResult) -> tuple:
    return (result.answer, result.grounding, result.semantics, result.format)


def failing_checks(result: ScoreResult) -> set:
    return {check.check_id for check in result.checks if check.applicable and check.score < 1.0}


def flip(color: str) -> str:
    return "black" if color == "white" else "white"


def to_rel1000(boxes: Sequence[Sequence[float]], size: Sequence[int]) -> List[List[float]]:
    width, height = size
    return [[b[0] * 1000 / width, b[1] * 1000 / height, b[2] * 1000 / width, b[3] * 1000 / height] for b in boxes]


def cell_boxes(record: TraceRecord, oracle: Mapping[str, Any]) -> Dict[int, List[float]]:
    """Board-cell box of every piece (oid -> box) from the persisted render map."""
    cells = record.render_map["cell_bboxes_px"]
    return {p["oid"]: list(cells[f"cell_r{p['row']}_c{p['col']}"]) for p in oracle["pieces"]}


def corruption_problems(result: ScoreResult, baseline: ScoreResult, corruption: Corruption) -> List[str]:
    """Mismatches between a corruption's expectation and its score (empty when it behaves)."""
    problems: List[str] = []
    expected_fail = {key for key, value in corruption.expected.items() if key not in SIGNALS and value == "fail"}
    if failing_checks(result) != expected_fail:
        problems.append(f"failing {sorted(failing_checks(result))} != expected {sorted(expected_fail)}")
    checks, reference_checks = by_id(result), by_id(baseline)
    for key, value in corruption.expected.items():
        if key in SIGNALS:
            actual, reference = getattr(result, SIGNALS[key]), getattr(baseline, SIGNALS[key])
        elif key in checks:
            actual, reference = checks[key].score, reference_checks[key].score
        else:
            problems.append(f"{key}: no such check")
            continue
        if isinstance(value, str):
            unchanged = abs(actual - reference) <= 0.01
            ok = {"pass": actual == 1.0, "fail": actual < 1.0, "unchanged": unchanged}.get(value)
        else:
            ok = abs(actual - float(value)) <= 1e-9
        if not ok:
            problems.append(f"{key}={actual:.4f} expected {value}")
    return problems


def permuted_object(obj: Mapping[str, Any], rng: random.Random) -> Dict[str, Any]:
    """Shuffle the annotation, re-bind every member's index, and shuffle the members."""
    order = list(range(len(obj["annotation"])))
    rng.shuffle(order)
    new_index = {old: new for new, old in enumerate(order)}
    members = [dict(m, annotation_index=new_index[m["annotation_index"]]) for m in obj["certificate"]["members"]]
    rng.shuffle(members)
    return {
        "annotation": [obj["annotation"][old] for old in order],
        "certificate": dict(obj["certificate"], members=members),
        "answer": obj["answer"],
    }


def reverse_keys(value: Any) -> Any:
    if isinstance(value, dict):
        return {key: reverse_keys(value[key]) for key in reversed(list(value))}
    if isinstance(value, list):
        return [reverse_keys(item) for item in value]
    return value


def wrong_operands(obj: Mapping[str, Any], rng: random.Random) -> Dict[str, Any]:
    """Misread the attributes of a random non-empty subset of members; count stays consistent."""
    out = copy.deepcopy(dict(obj))
    members = out["certificate"]["members"]
    for position in rng.sample(range(len(members)), rng.randint(1, len(members))):
        member = members[position]
        if rng.random() < 0.5:
            member["piece"] = rng.choice([kind for kind in PIECE_KINDS if kind != member["piece"]])
        else:
            member["color"] = flip(member["color"])
    out["certificate"]["count"] = out["answer"] = len(members)
    return out


def assert_perfect(result: ScoreResult) -> None:
    assert signals(result) == (1.0, 1.0, 1.0, 1.0), (
        result.diagnostics["format_reasons"],
        [c.to_dict() for c in result.checks if c.score < 1],
    )
    assert result.joint == 1.0 and result.error_class == "correct"
    assert all(check.score == 1.0 for check in result.checks if check.applicable)


def sweep_record(record: TraceRecord, seeds: Sequence[int] = (0, 1)) -> Dict[str, List[str]]:
    """Every adapter property on one record: ``{test name: [problems]}`` (empty lists pass)."""
    oracle = ADAPTER.build_oracle(record)
    ext = make_extension(record, oracle)
    obj = sft_object(oracle, record.instance_seed)
    base = score(obj, ext)
    out: Dict[str, List[str]] = {}
    out["roundtrip_unrounded"] = [] if signals(base) == (1, 1, 1, 1) else [str(signals(base))]

    result = score(dict(obj, annotation=[round_box_half_up(box) for box in obj["annotation"]]), ext)
    resolved = all(item["status"] == "resolved" for item in result.diagnostics["identity"][""])
    ok = (result.answer, result.semantics, result.format) == (1, 1, 1) and resolved
    out["roundtrip_rounded"] = [] if ok else [str(signals(result))]
    rel = dict(obj, annotation=to_rel1000(obj["annotation"], record.source_size()))
    result = score(rel, ext, coord_frame="rel1000")
    ok = (result.answer, result.semantics, result.format) == (1, 1, 1) and result.grounding > 0.999
    out["roundtrip_rel1000"] = [] if ok else [str(signals(result))]

    for corruption in ADAPTER.corruptions(oracle, obj, record.instance_seed):
        result = score(corruption.response_obj, ext)
        out[f"corruption:{corruption.name}"] = corruption_problems(result, base, corruption)
    if oracle["selected"]:
        out["property_wrong_operands"] = []
        for seed in seeds:
            checks = by_id(score(wrong_operands(obj, random.Random(seed)), ext))
            if not (checks["ss.attr.truth"].score < 1 and checks["ss.set.truth"].score == 1):
                out["property_wrong_operands"].append(f"seed {seed}")

    problems = [
        f"permuted {seed}"
        for seed in seeds
        if signals(score(permuted_object(obj, random.Random(seed)), ext)) != (1, 1, 1, 1)
    ]
    if signals(score(reverse_keys(obj), ext)) != (1, 1, 1, 1):
        problems.append("key order")
    cells = cell_boxes(record, oracle)
    if score(dict(obj, annotation=[cells[oid] for oid in oracle["selected"]]), ext).semantics != 1.0:
        problems.append("cell boxes")
    out["equivalence"] = problems
    return out


