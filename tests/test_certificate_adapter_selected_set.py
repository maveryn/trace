def test_named_corruption_scores(cases) -> None:
    """Spot values: denominators are max(n, k), gates close on a broken set, error classes."""
    case = next(_nonempty(cases, min_k=2))
    k = len(case["oracle"]["selected"])
    named = {c.name: c.response_obj for c in ADAPTER.corruptions(case["oracle"], sft_object(case["oracle"]), 0)}

    def run(name: str) -> ScoreResult:
        return score(named[name], case["ext"])

    duplicate = by_id(run("duplicate_member"))
    assert duplicate["ss.set.truth"].score == pytest.approx((k - 1) / (k + 1))
    assert duplicate["ss.count.truth"].error_code == "gate_closed"
    assert by_id(run("duplicate_box"))["ss.set.truth"].score == pytest.approx(k / (k + 1))
    assert run("empty_claim").semantics == 0.0 and run("empty_claim").error_class == "grounding"
    assert run("wrong_piece").error_class == "operand"
    assert by_id(run("wrong_piece"))["ss.attr.truth"].score == pytest.approx((k - 1) / k)
    assert run("wrong_count").error_class == "computation"
    assert run("answer_inconsistent").error_class == "answer_inconsistent"
    assert "element_invalid" in run("negative_index").diagnostics["format_reasons"]


