def _slim(record: TraceRecord) -> Dict[str, Any]:
    """Keep the persisted fields the adapter and tests read (fixture size); images are dropped."""
    trace = {key: copy.deepcopy(record.trace[key]) for key in _TRACE_KEEP if key in record.trace}
    pieces = [e for e in trace["scene_ir"]["entities"] if e.get("type") == "chess_piece"]
    trace["scene_ir"]["entities"] = pieces
    occupied = {f"cell_r{p['row']}_c{p['col']}" for p in pieces}
    cells = record.render_map["cell_bboxes_px"]
    trace["render_map"] = {
        "board_bbox_px": record.render_map.get("board_bbox_px"),
        "cell_bboxes_px": {key: box for key, box in cells.items() if key in occupied},
    }
    trace["execution_trace"] = {k: record.execution_trace[k] for k in _EXEC_KEEP if k in record.execution_trace}
    train = {key: value for key, value in record.train.items() if key not in _TRAIN_DROP}
    return {"train": train, "trace": trace, "image_size": list(record.source_size())}


def build_fixture(work_dir: Path) -> Dict[str, Any]:
    from trace_tasks import BuildConfig, BuildTaskConfig, build_dataset

    config = BuildConfig(
        output_root=str(work_dir),
        dataset_name="cert_selected_set_fixtures",
        instance_version="v0",
        image_format="png",
        tasks=[BuildTaskConfig(task_id=task, count=PER_TASK) for task in (COLORED_TASK, KIND_TASK)],
        max_attempts_per_instance=100,
        sampling_seed=SAMPLING_SEED,
        workers=1,
    )
    entries = []
    for record in read_trace_records(build_dataset(config, code_hash="cert-v1")):
        oracle = ADAPTER.build_oracle(record)
        entry = _slim(record)
        entry.update(
            oracle=oracle,
            sft=sft_object(oracle, record.instance_seed),
            split_cell=ADAPTER.split_cell(record),
            semantic_key=ADAPTER.semantic_key(record),
        )
        entries.append(entry)
    return {
        "description": "selected_set adapter fixtures: trimmed persisted chess records, oracle, SFT object",
        "sampling_seed": SAMPLING_SEED,
        "per_task": PER_TASK,
        "code_hash": "cert-v1",
        "trimmed": {
            "train": list(_TRAIN_DROP),
            "trace_kept": list(_TRACE_KEEP),
            "scene_ir.entities": "chess_piece only",
            "render_map": "board_bbox_px and cell_bboxes_px of occupied cells",
            "execution_trace_kept": list(_EXEC_KEEP),
            "images": "dropped; image_size kept",
        },
        "records": entries,
    }


