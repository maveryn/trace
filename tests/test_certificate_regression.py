"""Golden regression for the private legacy helpers the certificate scorer imports.

The certificate library imports four underscore-private helpers from
``trace_tasks.core.reward_scoring`` (DESIGN section 1): ``_score_trace_answer`` (A),
``_score_trace_annotation`` (G), ``_normalize_bbox`` (identity input) and
``_extract_final_json_object`` (final-object rule). This test pins their outputs, plus the
public ``score_trace_response``, on frozen records generated by ``trace_tasks`` for the five
supported tasks, so an upstream change cannot silently move A, G, F or identity.

Regenerate (only after an intentional upstream change, and review the diff):
    python -m tests.test_certificate_regression --regen <scratch_dir>
"""

