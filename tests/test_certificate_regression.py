def build_golden(work_dir: Path) -> Dict[str, Any]:
    """Generate one record per supported task and record every probe's legacy output."""
    from trace_tasks import BuildConfig, BuildTaskConfig, build_dataset
    from trace_tasks.experimental.certificates.types import read_trace_records

    work_dir.mkdir(parents=True, exist_ok=True)
    config = BuildConfig(
        output_root=str(work_dir),
        dataset_name="cert_legacy_golden",
        instance_version="v0",
        image_format="png",
        tasks=[BuildTaskConfig(task_id=task, count=1) for task in GOLDEN_TASKS],
        max_attempts_per_instance=100,
        sampling_seed=GOLDEN_SAMPLING_SEED,
        workers=1,
    )
    build_dataset(config, code_hash="cert-legacy-golden")
    dataset_dirs = sorted((work_dir / "datasets").iterdir())
    records = [record for directory in dataset_dirs for record in read_trace_records(directory)]
    records.sort(key=lambda record: GOLDEN_TASKS.index(record.task))
    keysets: List[List[str]] = []
    golden_records = [_record_golden(dict(r.train), list(r.source_size()), keysets) for r in records]
    return {
        "generator": {
            "sampling_seed": GOLDEN_SAMPLING_SEED,
            "code_hash": "cert-legacy-golden",
            "point_half_life_px": HALF_LIFE_PX,
            "command": "python -m tests.test_certificate_regression --regen <scratch_dir>",
        },
        "normalize_bbox": [
            {"value": value, "result": _normalize_bbox(copy.deepcopy(value))} for value in NORMALIZE_BBOX_PROBES
        ],
        "final_object": [
            {"response": text, "final": list(_extract_final_json_object(text))} for text in FINAL_OBJECT_PROBES
        ],
        "records": golden_records,
        "score_trace_keysets": keysets,
    }


if __name__ == "__main__":  # pragma: no cover - maintenance entry point
    if len(sys.argv) != 3 or sys.argv[1] != "--regen":
        raise SystemExit("usage: python -m tests.test_certificate_regression --regen <scratch_dir>")
    payload = build_golden(Path(sys.argv[2]))
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(json.dumps(payload, sort_keys=True, separators=(",", ":")) + "\n", encoding="utf-8")
    print(f"wrote {FIXTURE} ({FIXTURE.stat().st_size} bytes, {len(payload['records'])} records)")
