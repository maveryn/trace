_CONSTANT_PREFIXES = (
    "annotation_type_",
    "trace_reward_mode_",
    "trace_answer_scoring_",
    "trace_annotation_reward_formula_",
)
_CONSTANT_KEYS = ("trace_answer_weight", "trace_annotation_weight", "format_weight", "trace_reward")


def _jsonable(value: Any) -> Any:
    return json.loads(json.dumps(value, allow_nan=False))


def _split_constants(result: Dict[str, float]) -> tuple[Dict[str, float], Dict[str, float]]:
    """Split score_trace_response output into per-response values and per-config constants."""
    constant = {k: v for k, v in result.items() if k in _CONSTANT_KEYS or k.startswith(_CONSTANT_PREFIXES)}
    varying = {k: v for k, v in result.items() if k not in constant}
    return varying, constant


def _pack(varying: Dict[str, float], keysets: List[List[str]]) -> List[Any]:
    """Compact ``[keyset index, values...]`` encoding of one score dict (fixture size)."""
    keys = sorted(varying)
    if keys not in keysets:
        keysets.append(keys)
    return [keysets.index(keys)] + [varying[key] for key in keys]


def _unpack(packed: List[Any], keysets: List[List[str]]) -> Dict[str, float]:
    keys = keysets[packed[0]]
    assert len(keys) == len(packed) - 1
    return dict(zip(keys, packed[1:]))


def _shift(value: Any, dx: float) -> Any:
    if isinstance(value, list) and len(value) == 4 and all(isinstance(v, (int, float)) for v in value):
        return [value[0] + dx, value[1], value[2] + dx, value[3]]
    if isinstance(value, list):
        return [_shift(item, dx) for item in value]
    if isinstance(value, dict):
        return {key: _shift(item, dx) for key, item in value.items()}
    return value


def _annotation_probes(annotation_gt: Dict[str, Any]) -> Dict[str, Any]:
    value = annotation_gt["value"]
    far = [1.0, 1.0, 9.0, 9.0]
    probes: Dict[str, Any] = {"gt": value, "shift_10px": _shift(value, 10.0), "null": None}
    if isinstance(value, list):
        probes.update(
            {
                "drop_last": value[:-1],
                "extra_far": value + [far],
                "duplicate_first": value + value[:1],
                "empty": [],
                "reversed_corners": [[b[2], b[3], b[0], b[1]] for b in value],
                "zero_area": value[:-1] + [[5.0, 5.0, 5.0, 9.0]],
                "bool_coord": [[True, 2, 3, 4]] + value[1:],
                "single_box_not_list": value[0] if value else far,
                "bboxes_wrapper": {"bboxes": value},
            }
        )
    else:
        keys = sorted(value)
        probes.update(
            {
                "drop_key": {key: value[key] for key in keys[:-1]},
                "extra_key": dict(value, foo=value[keys[0]]),
                "empty": {},
                "list_instead_of_map": [value[keys[0]]],
                "swapped_roles": {keys[0]: value[keys[-1]], keys[-1]: value[keys[0]]},
            }
        )
        if all(isinstance(item, list) and item and isinstance(item[0], list) for item in value.values()):
            probes["drop_last_each"] = {key: value[key][:-1] for key in keys}
    return probes


def _answer_probes(answer_value: Any) -> List[Any]:
    return [
        answer_value,
        answer_value + 1,
        str(answer_value),
        float(answer_value),
        float(answer_value) + 0.5,
        f" {answer_value} ",
        f"{answer_value} units",
        True,
        False,
        "true",
        None,
        [answer_value],
        {"value": answer_value},
    ]


def _response_probes(answer_value: Any, annotation_value: Any) -> Dict[str, str]:
    obj = {"annotation": annotation_value, "answer": answer_value}
    compact = json.dumps(obj)
    cert = json.dumps({"annotation": annotation_value, "certificate": {"kind": "x"}, "answer": answer_value})
    return {
        "exact": compact,
        "swapped_key_order": json.dumps({"answer": answer_value, "annotation": annotation_value}),
        "with_certificate": cert,
        "prose_before": "I count carefully.\n" + compact,
        "trailing_prose": compact + "\nDone.",
        "fenced": "```json\n" + compact + "\n```",
        "answer_tag": "<answer>" + compact + "</answer>",
        "python_literal": str({"annotation": annotation_value, "answer": answer_value}),
        "duplicate_answer": compact[:-1] + ', "answer": ' + json.dumps(answer_value + 1) + "}",
        "nan_answer": json.dumps({"annotation": annotation_value, "answer": 0}).replace(
            '"answer": 0', '"answer": NaN'
        ),
        "wrong_answer": json.dumps({"annotation": annotation_value, "answer": answer_value + 1}),
        "null_annotation": json.dumps({"annotation": None, "answer": answer_value}),
        "answer_only": json.dumps({"answer": answer_value}),
        "bare_text": str(answer_value),
        "empty": "",
    }


def _record_golden(train: Dict[str, Any], image_size: List[int], keysets: List[List[str]]) -> Dict[str, Any]:
    answer_gt, annotation_gt, contract = train["answer_gt"], train["annotation_gt"], train["reward_contract"]
    answers = []
    for value in _answer_probes(answer_gt["value"]):
        score, parse_ok = _score_trace_answer(copy.deepcopy(value), answer_gt)
        answers.append({"value": value, "score": score, "parse_ok": parse_ok})
    annotations = {}
    for name, value in _annotation_probes(annotation_gt).items():
        score, parse_ok, details = _score_trace_annotation(
            copy.deepcopy(value), annotation_gt, contract, point_half_life_px=HALF_LIFE_PX
        )
        annotations[name] = {"value": value, "score": score, "parse_ok": parse_ok, "details": details}
    responses = {}
    constants: Dict[str, Dict[str, float]] = {}
    for name, text in _response_probes(answer_gt["value"], annotation_gt["value"]).items():
        final_text, found = _extract_final_json_object(text)
        scored = {}
        for config, kwargs in RESPONSE_CONFIGS.items():
            result = score_trace_response(
                response=text, answer_gt=answer_gt, annotation_gt=annotation_gt, reward_contract=contract, **kwargs
            )
            varying, constant = _split_constants(result)
            scored[config] = _pack(varying, keysets)
            assert constants.setdefault(config, constant) == constant
        responses[name] = {"response": text, "final": [final_text, found], "score_trace_response": scored}
    return _jsonable(
        {
            "task": train["task"],
            "query_id": train["query_id"],
            "instance_id": train["instance_id"],
            "image_size": image_size,
            "answer_gt": answer_gt,
            "annotation_gt": annotation_gt,
            "reward_contract": contract,
            "answer_probes": answers,
            "annotation_probes": annotations,
            "response_probes": responses,
            "score_trace_constants": constants,
        }
    )


def _assert_close(actual: Any, expected: Any, where: str) -> None:
    if isinstance(expected, dict):
        assert isinstance(actual, dict) and set(actual) == set(expected), where
        for key in expected:
            _assert_close(actual[key], expected[key], f"{where}.{key}")
    elif isinstance(expected, list):
        assert isinstance(actual, (list, tuple)) and len(actual) == len(expected), where
        for index, (a, e) in enumerate(zip(actual, expected)):
            _assert_close(a, e, f"{where}[{index}]")
    elif isinstance(expected, bool) or expected is None or isinstance(expected, str):
        assert actual == expected, f"{where}: {actual!r} != {expected!r}"
    else:
        assert math.isclose(float(actual), float(expected), rel_tol=1e-9, abs_tol=1e-9), (
            f"{where}: {actual!r} != {expected!r}"
        )


@pytest.fixture(scope="module")
def golden() -> Dict[str, Any]:
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def test_scipy_assignment_is_used() -> None:
    assert reward_scoring.linear_sum_assignment is not None


def test_golden_covers_every_supported_task(golden: Dict[str, Any]) -> None:
    assert {record["task"] for record in golden["records"]} == set(GOLDEN_TASKS)


def test_normalize_bbox_golden(golden: Dict[str, Any]) -> None:
    for probe in golden["normalize_bbox"]:
        _assert_close(_normalize_bbox(copy.deepcopy(probe["value"])), probe["result"], repr(probe["value"]))
    assert _normalize_bbox([0.0, 0.0, float("nan"), 1.0]) is None
    assert _normalize_bbox([0.0, 0.0, float("inf"), 1.0]) is None


def test_extract_final_json_object_golden(golden: Dict[str, Any]) -> None:
    for probe in golden["final_object"]:
        text, found = _extract_final_json_object(probe["response"])
        assert [text, found] == probe["final"], probe["response"]


def test_score_trace_answer_golden(golden: Dict[str, Any]) -> None:
    for record in golden["records"]:
        for probe in record["answer_probes"]:
            score, parse_ok = _score_trace_answer(copy.deepcopy(probe["value"]), record["answer_gt"])
            where = f"{record['task']} answer {probe['value']!r}"
            _assert_close([score, parse_ok], [probe["score"], probe["parse_ok"]], where)


def test_score_trace_annotation_golden(golden: Dict[str, Any]) -> None:
    for record in golden["records"]:
        for name, probe in record["annotation_probes"].items():
            score, parse_ok, details = _score_trace_annotation(
                copy.deepcopy(probe["value"]),
                record["annotation_gt"],
                record["reward_contract"],
                point_half_life_px=HALF_LIFE_PX,
            )
            where = f"{record['task']} annotation {name}"
            _assert_close(
                _jsonable({"score": score, "parse_ok": parse_ok, "details": details}),
                {key: probe[key] for key in ("score", "parse_ok", "details")},
                where,
            )
        assert record["annotation_probes"]["gt"]["score"] == 1.0


def test_score_trace_response_golden(golden: Dict[str, Any]) -> None:
    for record in golden["records"]:
        for name, probe in record["response_probes"].items():
            text, found = _extract_final_json_object(probe["response"])
            assert [text, found] == probe["final"], f"{record['task']} {name}"
            for config, kwargs in RESPONSE_CONFIGS.items():
                actual = score_trace_response(
                    response=probe["response"],
                    answer_gt=record["answer_gt"],
                    annotation_gt=record["annotation_gt"],
                    reward_contract=record["reward_contract"],
                    **kwargs,
                )
                varying, constant = _split_constants(actual)
                where = f"{record['task']} {name} {config}"
                expected = _unpack(probe["score_trace_response"][config], golden["score_trace_keysets"])
                _assert_close(varying, expected, where)
                _assert_close(constant, record["score_trace_constants"][config], where)


def test_golden_pins_known_legacy_quirks(golden: Dict[str, Any]) -> None:
    """The behaviours DESIGN 5 guards against must still be present upstream."""
    assert _score_trace_answer(True, {"type": "integer", "value": 1}) == (1.0, True)  # bool == 1
    assert _score_trace_answer("true", {"type": "integer", "value": 1}) == (1.0, True)
    record = next(r for r in golden["records"] if r["task"] == "task_physics__lever__side_torque_value")

    def scored(name: str, config: str) -> Dict[str, float]:
        packed = record["response_probes"][name]["score_trace_response"][config]
        return _unpack(packed, golden["score_trace_keysets"])

    assert scored("duplicate_answer", "release_answer")["accuracy"] == 0.0  # json.loads keeps the last
    assert scored("with_certificate", "annotation_gated")["format"] == 0.0  # extra key -> legacy F = 0
    assert scored("with_certificate", "annotation_gated")["annotation_reward"] == 1.0
    assert scored("python_literal", "release_answer")["accuracy"] == 1.0  # ast.literal_eval fallback
    assert scored("trailing_prose", "release_answer")["format"] == 0.0
    assert scored("nan_answer", "release_answer")["accuracy"] == 0.0


